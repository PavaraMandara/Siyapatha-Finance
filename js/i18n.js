  function current() {
    const saved = localStorage.getItem(KEY);
    return saved === "si" || saved === "ta" ? saved : "en";
  }

  function t(key) {
    const lang = current();
    const value = (pack[lang] && pack[lang][key]) || pack.en[key];
    return value == null ? "" : value;
  }

  function apply(root) {
    const scope = root || document;
    const lang = current();
    document.documentElement.lang = lang;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    scope.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    const title = document.querySelector("title[data-i18n]");
    if (title) title.textContent = t(title.getAttribute("data-i18n"));
    document.querySelectorAll("[data-lang]").forEach((btn) => {
      const on = btn.getAttribute("data-lang") === lang;
      btn.classList.toggle("is-on", on);
      btn.setAttribute("aria-pressed", on ? "true" : "false");
    });
  }

  function set(next) {
    if (!pack[next]) return;
    localStorage.setItem(KEY, next);
    apply();
    document.dispatchEvent(new CustomEvent("siyapatha-lang"));
  }

  if (!document.querySelector("link[data-i18n-font]")) {
    const font = document.createElement("link");
    font.rel = "stylesheet";
    font.setAttribute("data-i18n-font", "");
    font.href = "https://fonts.googleapis.com/css2?family=Noto+Sans+Sinhala:wght@500;600;700;800&family=Noto+Sans+Tamil:wght@500;600;700;800&display=swap";
    document.head.appendChild(font);
  }

  document.addEventListener("click", (event) => {
    const btn = event.target.closest("[data-lang]");
    if (!btn) return;
    set(btn.getAttribute("data-lang"));
  });

  window.I18n = { t: t, set: set, lang: current, apply: apply };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", () => apply());
  else apply();
